"""
    Unit tests for :mod:`automojo.webworks.security.passwords`.

    Two contracts to verify:

      1. Round-trip — :func:`hash_password` / :func:`verify_password`
         agree with each other across plaintext / wrong-plaintext /
         malformed-stored-hash inputs.

      2. **Wire compatibility with werkzeug.** Hashes generated by
         werkzeug's ``generate_password_hash(..., method="pbkdf2:sha256")``
         must verify against :func:`verify_password` so consumers can
         adopt this module without re-hashing their existing user
         records. The reverse direction is also exercised.

    The werkzeug-format fixture in
    ``test_verify_accepts_werkzeug_generated_hash`` was minted by
    ``werkzeug==2.3.8`` for the literal plaintext
    ``test-password-123`` with the default 600,000 PBKDF2 iterations.
    Any change to the format must keep this fixture verifying.
"""

from automojo.webworks.security.passwords import (
    DEFAULT_ITERATIONS,
    DEFAULT_SALT_LENGTH,
    hash_password,
    verify_password,
)


# =============================================================================
# Round-trip
# =============================================================================


def test_hash_then_verify_round_trips_for_correct_password():
    plaintext = "correct horse battery staple"

    stored = hash_password(plaintext)

    if not verify_password(plaintext, stored):
        errmsg = "Expected verify_password to accept the round-tripped hash"
        raise AssertionError(errmsg)

    return


def test_hash_then_verify_rejects_wrong_password():
    stored = hash_password("the right one")

    if verify_password("the wrong one", stored):
        errmsg = "Expected verify_password to reject a different plaintext"
        raise AssertionError(errmsg)

    return


def test_hash_password_produces_distinct_hashes_for_same_plaintext():
    """
        Each call to :func:`hash_password` mints a fresh salt, so the
        stored hash differs across calls even when the plaintext is
        identical. Catches a regression where the salt is reused or
        stripped from the stored format.
    """
    plaintext = "same-plaintext"

    first = hash_password(plaintext)
    second = hash_password(plaintext)

    if first == second:
        errmsg = (
            "hash_password should produce a unique hash per call "
            "(salt must differ); both calls returned {!r}".format(first)
        )
        raise AssertionError(errmsg)

    if not verify_password(plaintext, first):
        errmsg = "First hash must verify"
        raise AssertionError(errmsg)

    if not verify_password(plaintext, second):
        errmsg = "Second hash must verify"
        raise AssertionError(errmsg)

    return


