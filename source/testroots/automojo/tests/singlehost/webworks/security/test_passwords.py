def test_verify_rejects_empty_stored_hash():
    if verify_password("any", ""):
        errmsg = "Expected False for empty stored hash"
        raise AssertionError(errmsg)
    return


def test_verify_rejects_stored_with_too_few_segments():
    # Missing the hash segment.
    incomplete = "pbkdf2:sha256:600000$saltonly"

    if verify_password("any", incomplete):
        errmsg = "Expected False for stored hash with two segments"
        raise AssertionError(errmsg)
    return


def test_verify_rejects_stored_with_unknown_method():
    weird = "scrypt:n=16$saltvalue$abcdef"

    if verify_password("any", weird):
        errmsg = "Expected False for non-pbkdf2 method prefix"
        raise AssertionError(errmsg)
    return


def test_verify_rejects_stored_with_non_numeric_iterations():
    bad = "pbkdf2:sha256:notanumber$VBbkvqhZAW3UQtW6$00"

    if verify_password("any", bad):
        errmsg = "Expected False for non-numeric iteration count"
        raise AssertionError(errmsg)
    return


def test_verify_rejects_stored_with_zero_iterations():
    """
        Zero or negative iterations are treated as malformed input.
    """
    bad = "pbkdf2:sha256:0$saltvalue$00"

    if verify_password("any", bad):
        errmsg = "Expected False for zero iteration count"
        raise AssertionError(errmsg)
    return


def test_verify_returns_false_for_unknown_hash_name():
    """
        ``hashlib.pbkdf2_hmac`` raises ``ValueError`` for unknown hash
        names. The verifier must absorb that and return ``False``
        rather than propagating the exception to credential-check
        callers.
    """
    weird = "pbkdf2:nosuchhash:1000$saltvalue$00"

    if verify_password("any", weird):
        errmsg = "Expected False for unknown PBKDF2 hash algorithm"
        raise AssertionError(errmsg)
    return


def test_verify_rejects_non_string_arguments():
    if verify_password(None, hash_password("p")):  # type: ignore[arg-type]
        errmsg = "Expected False for non-string password"
        raise AssertionError(errmsg)

    if verify_password("p", None):  # type: ignore[arg-type]
        errmsg = "Expected False for non-string stored"
        raise AssertionError(errmsg)

    return


def test_hash_password_rejects_non_string_input():
    raised = False
    try:
        hash_password(None)  # type: ignore[arg-type]
    except TypeError:
        raised = True

    if not raised:
        errmsg = "Expected TypeError for non-string password"
        raise AssertionError(errmsg)

    return


# =============================================================================
# Iteration count round-trip
# =============================================================================


def test_iterations_round_trip_through_stored_format():
    """
        Hashes minted with a non-default iteration count store and
        verify against that count, not the current default. This is
        what lets the project raise ``DEFAULT_ITERATIONS`` over time
        without invalidating older hashes.
    """
    plaintext = "p"

    stored = hash_password(plaintext, iterations=100_000)

    if "100000" not in stored:
        errmsg = "Expected the non-default iteration count in the stored hash"
        raise AssertionError(errmsg)

    if not verify_password(plaintext, stored):
        errmsg = "Expected verify_password to round-trip a non-default iteration count"
        raise AssertionError(errmsg)

    return
