# Wire compatibility with werkzeug
# =============================================================================


def test_verify_accepts_werkzeug_generated_hash():
    """
        Hashes minted by werkzeug 2.3.x's
        ``generate_password_hash("test-password-123",
        method="pbkdf2:sha256")`` must verify here so existing user
        records survive the migration off werkzeug.
    """
    werkzeug_hash = (
        "pbkdf2:sha256:600000"
        "$VBbkvqhZAW3UQtW6"
        "$cf8a87e7b4fcaf10a755fb1364830ba7f192f01f3071c49778430ef910500705"
    )

    if not verify_password("test-password-123", werkzeug_hash):
        errmsg = (
            "verify_password must accept a werkzeug-generated hash for "
            "'test-password-123'"
        )
        raise AssertionError(errmsg)

    if verify_password("wrong-password", werkzeug_hash):
        errmsg = (
            "verify_password must reject a wrong plaintext against a "
            "werkzeug-generated hash"
        )
        raise AssertionError(errmsg)

    return


def test_hash_password_format_matches_werkzeug_shape():
    """
        :func:`hash_password` produces the format
        ``pbkdf2:sha256:<iter>$<salt>$<hexhash>`` that werkzeug also
        produces and accepts. Catches a regression where the format
        drifts (different separator, different method label,
        non-hex hash, …).
    """
    stored = hash_password("p")

    parts = stored.split("$")
    if len(parts) != 3:
        errmsg = "Expected three '$'-separated segments, got {!r}".format(stored)
        raise AssertionError(errmsg)

    method_spec, salt, hashed = parts

    if not method_spec.startswith("pbkdf2:sha256:"):
        errmsg = "Expected 'pbkdf2:sha256:<iter>' prefix, got {!r}".format(method_spec)
        raise AssertionError(errmsg)

    iter_text = method_spec.split(":")[2]
    if not iter_text.isdigit():
        errmsg = "Iteration count must be all-digits, got {!r}".format(iter_text)
        raise AssertionError(errmsg)

    if int(iter_text) != DEFAULT_ITERATIONS:
        errmsg = "Default iteration count drifted: got {}, expected {}".format(
            iter_text, DEFAULT_ITERATIONS
        )
        raise AssertionError(errmsg)

    if len(salt) != DEFAULT_SALT_LENGTH:
        errmsg = "Salt length drifted: got {}, expected {}".format(
            len(salt), DEFAULT_SALT_LENGTH
        )
        raise AssertionError(errmsg)

    # Hex digest is exactly 64 chars for SHA-256 (32 bytes -> 64 hex chars).
    if len(hashed) != 64:
        errmsg = "SHA-256 hex digest must be 64 chars, got {}".format(len(hashed))
        raise AssertionError(errmsg)

    int(hashed, 16)  # raises ValueError if not pure hex

    return


